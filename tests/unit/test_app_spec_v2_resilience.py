"""
test_app_spec_v2_resilience.py — Verification that AppSpecV2 gracefully handles LLM formatting variations.
"""

from __future__ import annotations

from ai_frappe_builder.models.app_spec_v2 import AppSpecV2, DocTypeSpec, FieldSpec


def test_llm_payload_with_name_and_object_roles():
    """
    Test the exact failure reported by the user:
    - LLM returns 'name' instead of 'app_name' and 'title'.
    - LLM returns roles as an array of dictionaries instead of list[str].
    """
    messy_payload = {
        "spec_version": "2.0",
        "status": "ready",
        "assumptions": ["Fleet tracking and repairs"],
        "app": {
            "name": "Vehicle Maintenance",
            "description": "App for tracking fleet vehicles and maintenance requests.",
            "roles": [
                {"role": "Fleet Manager", "description": "Manages fleet operations and maintenance requests."},
                {"role": "Maintenance Technician", "description": "Executes maintenance tasks."},
                {"role": "Fleet Auditor", "description": "Ensures safety and compliance."},
            ],
            "doctypes": [
                {
                    "name": "vehicle maintenance log",
                    "fields": [
                        {"fieldname": "vehicle plate", "label": "Vehicle Plate", "fieldtype": "string", "reqd": True},
                        {"fieldname": "cost", "label": "Cost", "fieldtype": "currency"},
                    ],
                }
            ],
        },
    }

    spec = AppSpecV2.model_validate(messy_payload)

    assert spec.app is not None
    assert spec.app.app_name == "vehicle_maintenance"
    assert spec.app.title == "Vehicle Maintenance"
    assert "Fleet Manager" in spec.app.roles
    assert "Maintenance Technician" in spec.app.roles
    assert "Fleet Auditor" in spec.app.roles
    assert "System Manager" in spec.app.roles
    assert all(isinstance(r, str) for r in spec.app.roles)

    # Check doctype normalization
    dt = spec.app.doctypes[0]
    assert dt.name == "Vehicle Maintenance Log"
    assert dt.fields[0].fieldname == "vehicle_plate"
    assert dt.fields[0].fieldtype == "Data"
    assert dt.fields[1].fieldtype == "Currency"


def test_top_level_doctypes_without_app_container():
    """
    Test when LLM places doctypes and app_name at top-level without nesting in 'app'.
    """
    top_level_payload = {
        "spec_version": "2.0",
        "status": "ready",
        "name": "Clinic Manager",
        "roles": "Doctor, Nurse, Receptionist",
        "doctypes": [
            {
                "name": "Patient Appointment",
                "fields": [
                    {"fieldname": "patient_name", "label": "Patient Name", "fieldtype": "Data", "reqd": True}
                ],
            }
        ],
    }

    spec = AppSpecV2.model_validate(top_level_payload)
    assert spec.app is not None
    assert spec.app.app_name == "clinic_manager"
    assert spec.app.title == "Clinic Manager"
    assert "Doctor" in spec.app.roles
    assert "Nurse" in spec.app.roles
    assert "Receptionist" in spec.app.roles
    assert len(spec.app.doctypes) == 1
    assert spec.app.doctypes[0].name == "Patient Appointment"


def test_workflow_extra_attributes_ignored():
    """
    Ensure extra attributes generated by LLM on WorkflowState or Transition don't cause forbid errors.
    """
    wf_payload = {
        "name": "Approval Workflow",
        "doctype": "Purchase Request",
        "states": [
            {
                "state": "Draft",
                "doc_status": 0,
                "allow_edit": {"role": "Purchaser", "level": 1},
                "comment": "Initial draft state",
            },
            {
                "state": "Approved",
                "doc_status": 1,
                "allow_edit": "Manager",
                "extra_key": "some value",
            },
        ],
        "transitions": [
            {
                "state": "Draft",
                "action": "Approve",
                "next_state": "Approved",
                "allow_role": {"role": "Manager"},
                "extra_metadata": 123,
            }
        ],
    }

    spec = AppSpecV2.model_validate(
        {
            "app": {
                "app_name": "purchasing",
                "title": "Purchasing",
                "workflows": [wf_payload],
            }
        }
    )

    assert spec.app is not None
    wf = spec.app.workflows[0]
    assert len(wf.states) == 2
    assert wf.states[0].allow_edit == "Purchaser"
    assert wf.transitions[0].allowed == "Manager"
