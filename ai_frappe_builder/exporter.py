"""
exporter.py — Export a built AppSpec into a real installable Frappe app.

Output structure:
  {output_dir}/{app_name}/
    {app_name}/
      __init__.py
      hooks.py
      modules.txt
      {module_name}/
        doctype/
          {doctype_snake}/
            {doctype_snake}.json       ← DocType JSON export
            {doctype_snake}.py         ← Controller stub
            __init__.py
        report/
          {report_name_snake}/
            {report_name_snake}.json
            {report_name_snake}.py
        workspace/
          {workspace_name_snake}/
            {workspace_name_snake}.json
    setup.py
    README.md
    .gitignore
"""

import json
import os
import shutil
import subprocess
import re
from pathlib import Path
from datetime import datetime

from models import AppSpec, DocTypeSpec


def snake(name: str) -> str:
    """'Rental Agreement' → 'rental_agreement'"""
    return name.lower().replace(" ", "_").replace("-", "_")


def generate_doctype_json(dt_spec: DocTypeSpec) -> dict:
    """Generate the JSON that Frappe uses to define a DocType (for fixtures)."""
    fields = []
    for f in dt_spec.fields:
        field_dict = {
            "fieldname": f.fieldname,
            "fieldtype": f.fieldtype,
            "label": f.label,
            "reqd": 1 if f.reqd else 0,
            "in_list_view": 1 if f.in_list_view else 0,
            "in_standard_filter": 1 if f.in_standard_filter else 0,
        }
        if f.options:
            field_dict["options"] = f.options
        if f.default:
            field_dict["default"] = f.default
        fields.append(field_dict)

    permissions = []
    for p in dt_spec.permissions:
        permissions.append({
            "role": p.role,
            "read": 1 if p.read else 0,
            "write": 1 if p.write else 0,
            "create": 1 if p.create else 0,
            "delete": 1 if p.delete else 0,
            "submit": 1 if p.submit else 0,
            "cancel": 1 if p.cancel else 0,
        })

    return {
        "doctype": "DocType",
        "name": dt_spec.name,
        "module": dt_spec.module,
        "istable": 1 if dt_spec.istable else 0,
        "is_submittable": 1 if dt_spec.is_submittable else 0,
        "is_single": 1 if dt_spec.is_single else 0,
        "track_changes": 1 if dt_spec.track_changes else 0,
        "autoname": dt_spec.autoname,
        "fields": fields,
        "permissions": permissions,
        "creation": datetime.now().isoformat(),
        "modified": datetime.now().isoformat(),
    }


def generate_hooks(app_name: str, app_title: str, modules: list[str], has_scheduler: bool = False) -> str:
    """Generate hooks.py content."""
    scheduler_block = """
scheduler_events = {
    "daily": [
        # Add your scheduled tasks here
    ],
}
""" if has_scheduler else ""

    return f'''# -*- coding: utf-8 -*-
from __future__ import unicode_literals

app_name = "{app_name}"
app_title = "{app_title}"
app_publisher = "AI Frappe Builder"
app_description = "Auto-generated by AI Frappe App Builder"
app_version = "0.0.1"
app_email = "builder@example.com"
app_license = "MIT"

# Includes in <head>
# ------------------

# include js, css files in header of desk.html
# app_include_css = "/assets/{app_name}/css/custom.css"
# app_include_js = "/assets/{app_name}/js/custom.js"

# Home Pages
# ----------

# application home page (will override Website Settings)
# home_page = "login"

# Fixtures
# --------
fixtures = ["Custom Field", "Property Setter", "Role"]
{scheduler_block}
'''


def generate_controller(doctype_name: str, module: str) -> str:
    """Generate a minimal Python controller stub."""
    class_name = doctype_name.replace(" ", "")
    return f'''# -*- coding: utf-8 -*-
# Copyright (c) {datetime.now().year}, AI Frappe Builder and contributors
# For license information, please see license.txt

import frappe
from frappe.model.document import Document


class {class_name}(Document):
    """Controller for {doctype_name}."""

    def validate(self):
        pass

    def before_save(self):
        pass

    def on_submit(self):
        pass

    def on_cancel(self):
        pass
'''


def generate_setup_py(app_name: str, app_title: str) -> str:
    return f'''from setuptools import setup, find_packages

with open("requirements.txt") as f:
    install_requires = f.read().strip().split("\\n")

setup(
    name="{app_name}",
    version="0.0.1",
    description="Auto-generated by AI Frappe App Builder",
    author="AI Frappe Builder",
    author_email="builder@example.com",
    packages=find_packages(),
    zip_safe=False,
    include_package_data=True,
    install_requires=install_requires,
)
'''


def generate_readme(app_title: str, assumptions: list[str], modules: list[str]) -> str:
    assumptions_text = "\n".join(f"- {a}" for a in assumptions) if assumptions else "- No assumptions recorded"
    modules_text = "\n".join(f"- {m}" for m in modules)
    return f'''# {app_title}

Auto-generated by AI Frappe App Builder.

## Installation

```bash
bench get-app {app_title.lower().replace(" ", "_")} <repo_url>
bench --site your-site install-app {app_title.lower().replace(" ", "_")}
bench migrate
```

## Modules

{modules_text}

## Assumptions

{assumptions_text}

## License

MIT
'''


async def export_app(
    spec: AppSpec,
    output_dir: str = "/tmp/frappe_exports",
    git_remote: str | None = None,
) -> dict:
    """
    Export the AppSpec as a real Frappe app directory.

    Returns:
        {
            "app_path": str,
            "app_name": str,
            "files_created": list[str],
            "git_initialized": bool,
            "git_remote": str | None,
            "errors": list[str],
        }
    """
    if not spec.app:
        return {"errors": ["No app spec to export"]}

    app_data = spec.app
    app_name = app_data.get("app_name", "generated_app")
    app_title = app_data.get("title", app_name.replace("_", " ").title())
    modules = app_data.get("modules", [app_title])
    assumptions = spec.assumptions or []

    errors = []
    files_created = []

    # Root of the Frappe app
    app_root = Path(output_dir) / app_name / app_name
    app_root.mkdir(parents=True, exist_ok=True)

    # Write __init__.py
    init_file = app_root / "__init__.py"
    init_file.write_text("__version__ = '0.0.1'\n")
    files_created.append(str(init_file))

    # Write modules.txt
    modules_txt = app_root / "modules.txt"
    modules_txt.write_text("\n".join(modules))
    files_created.append(str(modules_txt))

    # Parse doctypes
    doctypes = spec.get_doctypes()
    has_scheduler = bool(app_data.get("server_scripts", []))

    # Write hooks.py
    hooks_file = app_root / "hooks.py"
    hooks_file.write_text(generate_hooks(app_name, app_title, modules, has_scheduler))
    files_created.append(str(hooks_file))

    # Write setup.py at the outer level
    outer_root = Path(output_dir) / app_name
    setup_file = outer_root / "setup.py"
    setup_file.write_text(generate_setup_py(app_name, app_title))
    files_created.append(str(setup_file))

    # Write requirements.txt
    req_file = outer_root / "requirements.txt"
    req_file.write_text("frappe\n")
    files_created.append(str(req_file))

    # Write README
    readme_file = outer_root / "README.md"
    readme_file.write_text(generate_readme(app_title, assumptions, modules))
    files_created.append(str(readme_file))

    # Write .gitignore
    gitignore = outer_root / ".gitignore"
    gitignore.write_text("*.pyc\n__pycache__/\n*.egg-info/\n.env\n*.db\n")
    files_created.append(str(gitignore))

    # Write DocType files
    for dt in doctypes:
        module_snake = snake(dt.module)
        dt_snake = snake(dt.name)

        dt_dir = app_root / module_snake / "doctype" / dt_snake
        dt_dir.mkdir(parents=True, exist_ok=True)

        # __init__.py
        (dt_dir / "__init__.py").write_text("")
        files_created.append(str(dt_dir / "__init__.py"))

        # DocType JSON
        dt_json_path = dt_dir / f"{dt_snake}.json"
        dt_json_path.write_text(json.dumps(generate_doctype_json(dt), indent=2))
        files_created.append(str(dt_json_path))

        # Controller .py
        controller_path = dt_dir / f"{dt_snake}.py"
        controller_path.write_text(generate_controller(dt.name, dt.module))
        files_created.append(str(controller_path))

    # Write server scripts as .py files in a scripts/ dir
    for script in app_data.get("server_scripts", []):
        if script.get("script"):
            scripts_dir = app_root / "server_scripts"
            scripts_dir.mkdir(exist_ok=True)
            script_file = scripts_dir / f"{snake(script['name'])}.py"
            script_file.write_text(
                f"# {script.get('purpose', '')}\n# Pattern: {script.get('pattern', '')}\n\n{script['script']}"
            )
            files_created.append(str(script_file))

    # Git init
    git_initialized = False
    try:
        subprocess.run(["git", "init"], cwd=str(outer_root), check=True, capture_output=True)
        subprocess.run(["git", "add", "."], cwd=str(outer_root), check=True, capture_output=True)
        subprocess.run(
            ["git", "commit", "-m", f"Initial commit: {app_title} generated by AI Frappe App Builder"],
            cwd=str(outer_root),
            check=True,
            capture_output=True,
            env={
                **os.environ,
                "GIT_AUTHOR_NAME": "AI Frappe Builder",
                "GIT_AUTHOR_EMAIL": "builder@example.com",
                "GIT_COMMITTER_NAME": "AI Frappe Builder",
                "GIT_COMMITTER_EMAIL": "builder@example.com",
            },
        )
        git_initialized = True

        if git_remote:
            subprocess.run(
                ["git", "remote", "add", "origin", git_remote],
                cwd=str(outer_root),
                check=True,
                capture_output=True,
            )
            subprocess.run(
                ["git", "push", "-u", "origin", "main"],
                cwd=str(outer_root),
                capture_output=True,
            )
    except subprocess.CalledProcessError as e:
        errors.append(f"Git error: {e}")
    except FileNotFoundError:
        errors.append("git not found in PATH")

    # Generate zip archive
    zip_path = None
    try:
        archive_name = str(Path(output_dir) / f"{app_name}")
        created_zip = shutil.make_archive(archive_name, "zip", str(outer_root))
        zip_path = created_zip
    except Exception as z_err:
        errors.append(f"Zip creation error: {z_err}")

    return {
        "app_path": str(outer_root),
        "app_name": app_name,
        "zip_path": zip_path,
        "files_created": files_created,
        "git_initialized": git_initialized,
        "git_remote": git_remote,
        "errors": errors,
    }
